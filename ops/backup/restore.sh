#!/bin/sh
set -eu
umask 077

PROJECT_ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd -P)
if [ "$PROJECT_ROOT" != '/opt/wechat-vault' ]; then
    printf '%s\n' 'Run the deployed restore script from its deployed /opt/wechat-vault/ops subdirectory.' >&2
    exit 1
fi
if [ "$#" -ne 2 ] || [ "$2" != '--confirm-replace' ]; then
    printf '%s\n' 'Usage: restore.sh /absolute/path/to/backup.tar.gz --confirm-replace' >&2
    printf '%s\n' 'This replaces the current vault with the selected backup. The app is restarted locked.' >&2
    exit 1
fi
if [ "$(id -u)" -ne 0 ]; then
    printf '%s\n' 'Run restore as root so the envelope file keeps the app ownership.' >&2
    exit 1
fi
ARCHIVE=$1
if [ ! -f "$ARCHIVE" ] || [ -L "$ARCHIVE" ]; then
    printf '%s\n' 'The backup must be a regular archive file, not a link.' >&2
    exit 1
fi
BACKUP_ROOT="$PROJECT_ROOT/backups"
if [ -L "$BACKUP_ROOT" ]; then
    printf '%s\n' 'Refusing a symlink as the backup directory.' >&2
    exit 1
fi
mkdir -p -- "$BACKUP_ROOT"
if [ "$(CDPATH= cd -- "$BACKUP_ROOT" && pwd -P)" != "$PROJECT_ROOT/backups" ]; then
    printf '%s\n' 'Backup directory is outside the project.' >&2
    exit 1
fi

exec 8>"$BACKUP_ROOT/.restore.lock"
if ! flock -n 8; then
    printf '%s\n' 'Another restore is already running.' >&2
    exit 1
fi

# Only the two files generated by backup.sh are accepted; extraction cannot
# introduce paths, symlinks, duplicate members, or arbitrary executable files.
EXPECTED=$(printf 'database.dump\nvault.json')
if [ "$(tar -tzf "$ARCHIVE" | LC_ALL=C sort)" != "$EXPECTED" ]; then
    printf '%s\n' 'The archive does not contain exactly database.dump and vault.json.' >&2
    exit 1
fi
if [ "$(tar -tvzf "$ARCHIVE" | cut -c 1 | LC_ALL=C sort -u)" != '-' ]; then
    printf '%s\n' 'The backup must contain regular files only.' >&2
    exit 1
fi
STAGING=$(mktemp -d "$BACKUP_ROOT/.restore-XXXXXXXX")
cleanup() {
    case "$STAGING" in
        "$BACKUP_ROOT"/.restore-*) rm -rf -- "$STAGING" ;;
    esac
}
trap cleanup EXIT
trap 'exit 1' HUP INT TERM
tar -xzf "$ARCHIVE" -C "$STAGING" --no-same-owner --no-same-permissions database.dump vault.json
for FILE in database.dump vault.json; do
    if [ ! -f "$STAGING/$FILE" ] || [ -L "$STAGING/$FILE" ]; then
        printf '%s\n' 'The archive contains an invalid file type.' >&2
        exit 1
    fi
done
python3 - "$STAGING/vault.json" <<'PY'
import base64
import json
import sys

with open(sys.argv[1], encoding="utf-8") as source:
    value = json.load(source)
if value.get("version") != 1:
    raise SystemExit("Unsupported envelope version.")
for field in ("salt", "wrapped", "recovery"):
    if not isinstance(value.get(field), str):
        raise SystemExit("Invalid envelope structure.")
    base64.b64decode(value[field], validate=True)
if not all(isinstance(value.get(field), int) and value[field] > 0 for field in ("ops", "mem")):
    raise SystemExit("Invalid envelope parameters.")
PY

COMPOSE_FILE="$PROJECT_ROOT/compose.yaml"
ENVELOPE="$PROJECT_ROOT/data/vault/vault.json"
docker compose -f "$COMPOSE_FILE" up -d db
READY=0
while ! docker compose -f "$COMPOSE_FILE" exec -T -u postgres db pg_isready -U postgres -d vault >/dev/null 2>&1; do
    READY=$((READY + 1))
    if [ "$READY" -ge 30 ]; then
        printf '%s\n' 'PostgreSQL did not become ready.' >&2
        exit 1
    fi
    sleep 2
done
if [ -f "$ENVELOPE" ]; then
    "$PROJECT_ROOT/ops/backup/backup.sh"
fi
exec 9>"$BACKUP_ROOT/.backup.lock"
flock -x 9

docker compose -f "$COMPOSE_FILE" stop app
# --single-transaction leaves the current database intact if restoration fails.
# Restoring as vault_app keeps table ownership consistent with app migrations.
docker compose -f "$COMPOSE_FILE" exec -T -u postgres db \
    pg_restore --clean --if-exists --no-owner --role=vault_app --exit-on-error \
    --single-transaction -U postgres -d vault < "$STAGING/database.dump"
install -d -o 10001 -g 70 -m 700 "$PROJECT_ROOT/data/vault"
install -o 10001 -g 70 -m 600 "$STAGING/vault.json" "$ENVELOPE.restore"
mv -- "$ENVELOPE.restore" "$ENVELOPE"
rm -f -- "$PROJECT_ROOT/data/vault/query-unlock.json"
"$PROJECT_ROOT/ops/security/init-query-key.sh"
docker compose -f "$COMPOSE_FILE" up -d app
printf '%s\n' 'Restore complete. Log in once with the matching master password or recovery key to enable unattended queries on this host.'
